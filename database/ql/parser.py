from typing import List
from database.ql.token import Token
from database.ql.lexer import Lexer
from database.ql.ast_node import ASTNode
from database.ql.constants import TokenType
from database.ql.constants import ASTNodeType
from database.ql.exceptions import QLError


class Parser:
  """
  Parser
  ======
  Parser class is responsible for parsing the tokens generated by the lexer
  and constructing an abstract syntax tree (AST) for the input program.
  """

  def __init__(self, lexer: Lexer):
    self._lexer = lexer
    self._cur_token: Token = Token(0, 0, TokenType.EOF, TokenType.EOF.value)

  # ========================================================================= #
  # Internal API                                                              #
  # ========================================================================= #

  def _error(
      self, token: Token, message: str = ""
  ) -> QLError:
    return QLError(self._lexer.text, token.line, token.column, message)

  def _eat(self, token_type: TokenType):
    if self._cur_token.type == token_type:
      self._cur_token = self._lexer.next_token()
    else:
      raise self._error(self._cur_token, f"Expect {token_type.value}")

  def _id_token(self) -> Token:
    id_ = self.cur_token
    self._eat(TokenType.ID)
    return id_

  # ========================================================================= #
  # Parser methods                                                            #
  # ========================================================================= #

  # ------------------------------------------------------------------------- #
  # Statements                                                                #
  # ------------------------------------------------------------------------- #

  def _table_name(self) -> ASTNode:
    table_name = self._id_token()
    return ASTNode(ASTNodeType.ID, table_name)

  def _field_name(self) -> ASTNode:
    field_name = self._id_token()
    return ASTNode(ASTNodeType.ID, field_name)

  def _statements(self) -> ASTNode:
    token = self.cur_token
    node = []
    while self.cur_token.type != TokenType.EOF:
      node.append(self._statement())
      self._eat(TokenType.SEMICOLON)
    return ASTNode(ASTNodeType.STATEMENTS, token, node)

  def _statement(self) -> ASTNode:
    token = self.cur_token
    if token.type == TokenType.CREATE:
      return self._create_table()
    if token.type == TokenType.DROP:
      return self._drop_table()
    if token.type == TokenType.SELECT:
      return self._select()
    if token.type == TokenType.INSERT:
      return self._insert()
    if token.type == TokenType.UPDATE:
      return self._update()
    if token.type == TokenType.DELETE:
      return self._delete()
    raise self._error(token, f"Unexpected token: {token.type.value}")

  # ------------------------------------------------------------------------- #
  # Table                                                                     #
  # ------------------------------------------------------------------------- #

  def _create_table(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.CREATE)
    self._eat(TokenType.TABLE)
    table_name = self._table_name()
    self._eat(TokenType.LEFT_PAREN)
    children = self._declarations()
    self._eat(TokenType.RIGHT_PAREN)
    res = ASTNode(ASTNodeType.CREATE_TABLE, token, [table_name, children])
    return res

  def _drop_table(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.DROP)
    self._eat(TokenType.TABLE)
    table_name = self._table_name()
    return ASTNode(ASTNodeType.DROP_TABLE, token, [table_name])

  def _declarations(self) -> ASTNode:
    fields, indexes = [self._field_decl()], []
    is_index = False
    while self.cur_token.type == TokenType.COMMA:
      self._eat(TokenType.COMMA)
      if self.cur_token.type == TokenType.PRIMARY:
        break
      if not is_index and self.cur_token.type == TokenType.ID:
        fields.append(self._field_decl())
        continue
      is_index = True
      indexes.append(self._index_decl())
    primary_key = self._primary_key_decl()
    return ASTNode(
        ASTNodeType.DECLARATIONS, self.cur_token,
        [
            ASTNode(ASTNodeType.FIELD_DECLS, self.cur_token, fields),
            ASTNode(ASTNodeType.INDEX_DECLS, self.cur_token, indexes),
            primary_key
        ]
    )

  def _field_decl(self) -> ASTNode:
    token = self.cur_token
    field_name = self._field_name()
    field_type = self._field_type()
    return ASTNode(ASTNodeType.FIELD_DECL, token, [field_name, field_type])

  def _field_type(self) -> ASTNode:
    token = self.cur_token
    if token.type in [TokenType.INTEGER, TokenType.TEXT]:
      self._eat(token.type)
      return ASTNode(ASTNodeType.TYPE, token)
    raise self._error(token, f"Invalid type: {token.type.name}")

  def _index_decl(self) -> ASTNode:
    self._eat(TokenType.INDEX)
    return ASTNode(ASTNodeType.INDEX_DECL, self._id_token(), [])

  def _primary_key_decl(self) -> ASTNode:
    self._eat(TokenType.PRIMARY)
    self._eat(TokenType.KEY)
    return ASTNode(ASTNodeType.PRIMARY_KEY_DECLS, self._id_token(), [])

  def _tuple_decl(self) -> List[ASTNode]:
    self._eat(TokenType.LEFT_PAREN)
    decls = [self._field_name()]
    while self.cur_token.type == TokenType.COMMA:
      self._eat(TokenType.COMMA)
      decls.append(self._field_name())
    self._eat(TokenType.RIGHT_PAREN)
    return decls

  # ------------------------------------------------------------------------- #
  # Select                                                                    #
  # ------------------------------------------------------------------------- #

  def _select(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.SELECT)
    fields = self._select_expr()
    self._eat(TokenType.FROM)
    table = self._table_name()
    conditions = self._conditions()
    offset = self._offset()
    limit = self._limit()
    return ASTNode(
        ASTNodeType.SELECT, token, [fields, table, conditions, offset, limit]
    )

  def _select_expr(self) -> ASTNode:
    if self.cur_token.type == TokenType.LEFT_PAREN:
      self._eat(TokenType.LEFT_PAREN)
      select_expr = self._select_expr()
      self._eat(TokenType.RIGHT_PAREN)
      return select_expr
    token = self.cur_token
    as_exprs = [self._as_expr()]
    while self.cur_token.type == TokenType.COMMA:
      self._eat(TokenType.COMMA)
      as_exprs.append(self._as_expr())
    return ASTNode(ASTNodeType.SELECT_EXPR, token, as_exprs)

  def _as_expr(self) -> ASTNode:
    token = self.cur_token
    fields = [self._field_name()]
    while self.cur_token.type == TokenType.AS:
      self._eat(TokenType.AS)
      fields.append(self._field_name())
    return ASTNode(ASTNodeType.AS_EXPR, token, fields)

  def _conditions(self) -> ASTNode:
    token = self.cur_token
    children = []
    if self.cur_token.type == TokenType.INDEX:
      children.append(self._index())
    else:
      children.append(ASTNode(ASTNodeType.INDEX, self.cur_token, []))
    if self.cur_token.type == TokenType.FILTER:
      children.append(self._filter())
    else:
      children.append(ASTNode(ASTNodeType.FILTER, self.cur_token, []))
    return ASTNode(ASTNodeType.CONDITIONS, token, children)

  def _offset(self) -> ASTNode:
    token = self.cur_token
    if self.cur_token.type == TokenType.OFFSET:
      self._eat(TokenType.OFFSET)
      return ASTNode(ASTNodeType.OFFSET, token, [self._number()])
    return ASTNode(ASTNodeType.OFFSET, token, [])

  def _limit(self) -> ASTNode:
    token = self.cur_token
    if self.cur_token.type == TokenType.LIMIT:
      self._eat(TokenType.LIMIT)
      return ASTNode(ASTNodeType.LIMIT, token, [self._number()])
    return ASTNode(ASTNodeType.LIMIT, token, [])

  def _index(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.INDEX)
    self._eat(TokenType.BY)
    nodes = [self._condition()]
    if self.cur_token.type == TokenType.AND:
      self._eat(TokenType.AND)
      nodes.append(self._condition())
    return ASTNode(ASTNodeType.INDEX, token, nodes)

  def _filter(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.FILTER)
    self._eat(TokenType.BY)
    node = self._condition()
    while self.cur_token.type in [TokenType.AND, TokenType.OR]:
      logic_token = self.cur_token
      self._eat(self.cur_token.type)
      node = ASTNode(ASTNodeType.LOGIC, logic_token, [node, self._condition()])
    return ASTNode(ASTNodeType.FILTER, token, [node])

  def _condition(self) -> ASTNode:
    left = self._field_name()
    op = self.cur_token
    if op.type in [
        TokenType.EQ, TokenType.NEQ, TokenType.LT,
        TokenType.LE, TokenType.GT, TokenType.GE,
    ]:
      self._eat(op.type)
    else:
      raise self._error(op, f"Invalid operator: {op.value}")
    right = self._logic()
    return ASTNode(ASTNodeType.CONDITION, op, [left, right])

  # ------------------------------------------------------------------------- #
  # Insert                                                                    #
  # ------------------------------------------------------------------------- #

  def _insert(self):
    self._eat(TokenType.INSERT)
    self._eat(TokenType.INTO)
    table = self._table_name()
    fields = ASTNode(
        ASTNodeType.TUPLE_DECLS, self.cur_token, self._tuple_decl()
    )
    self._eat(TokenType.VALUES)
    values = self._tuple_values()
    return ASTNode(
        ASTNodeType.INSERT, self.cur_token, [table, fields, values]
    )

  def _tuple_values(self) -> ASTNode:
    self._eat(TokenType.LEFT_PAREN)
    values = [self._value()]
    while self.cur_token.type == TokenType.COMMA:
      self._eat(TokenType.COMMA)
      values.append(self._comparison())
    self._eat(TokenType.RIGHT_PAREN)
    return ASTNode(ASTNodeType.TUPLE_VALUES, self.cur_token, values)

  # ------------------------------------------------------------------------- #
  # Update                                                                    #
  # ------------------------------------------------------------------------- #

  def _update(self) -> ASTNode:
    token = self.cur_token
    self._eat(TokenType.UPDATE)
    table = self._table_name()
    self._eat(TokenType.SET)
    set_exprs = ASTNode(
        ASTNodeType.SET_EXPRS, self.cur_token, [self._set_expr()]
    )
    while self.cur_token.type == TokenType.COMMA:
      self._eat(TokenType.COMMA)
      set_exprs.children.append(self._set_expr())
    conditions = self._conditions()
    offset = self._offset()
    limit = self._limit()
    return ASTNode(
        ASTNodeType.UPDATE, token, [table, set_exprs, conditions, offset, limit]
    )

  def _set_expr(self) -> ASTNode:
    token = self.cur_token
    field = self._field_name()
    self._eat(TokenType.EQ)
    value = self._comparison()
    return ASTNode(ASTNodeType.SET_EXPR, token, [field, value])

  # ------------------------------------------------------------------------- #
  # Delete                                                                    #
  # ------------------------------------------------------------------------- #

  def _delete(self) -> ASTNode:
    self._eat(TokenType.DELETE)
    self._eat(TokenType.FROM)
    table = self._table_name()
    conditions = self._conditions()
    offset = self._offset()
    limit = self._limit()
    return ASTNode(
        ASTNodeType.DELETE, self.cur_token, [table, conditions, offset, limit]
    )

  # ------------------------------------------------------------------------- #
  # Expression                                                                #
  # ------------------------------------------------------------------------- #

  def _value(self) -> ASTNode:
    if isinstance(self.cur_token.value, int):
      return self._number()
    if isinstance(self.cur_token.value, str):
      return self._string()
    raise self._error(self.cur_token, f"Invalid value: {self.cur_token.value}")

  def _number(self) -> ASTNode:
    token = self.cur_token
    if not isinstance(token.value, int):
      raise self._error(token, f"Invalid number: {token.value}")
    self._eat(TokenType.VALUE)
    return ASTNode(ASTNodeType.NUMBER, token)

  def _string(self) -> ASTNode:
    token = self.cur_token
    if not isinstance(token.value, str):
      raise self._error(token, f"Invalid string: {token.value}")
    self._eat(TokenType.VALUE)
    return ASTNode(ASTNodeType.STRING, token)

  def _logic(self) -> ASTNode:
    comparison = self._comparison()
    while self.cur_token.type in [
        TokenType.EQ, TokenType.NEQ, TokenType.LT,
        TokenType.LE, TokenType.GT, TokenType.GE,
    ]:
      token = self.cur_token
      self._eat(token.type)
      comparison = ASTNode(
          ASTNodeType.COMPARISON, token, [comparison, self._comparison()]
      )
    return comparison

  def _comparison(self) -> ASTNode:
    term = self._term()
    while self.cur_token.type in [TokenType.PLUS, TokenType.MINUS]:
      token = self.cur_token
      self._eat(token.type)
      term = ASTNode(ASTNodeType.ARITHMETIC, token, [term, self._term()])
    return term

  def _term(self) -> ASTNode:
    factor = self._factor()
    while self.cur_token.type in [
        TokenType.STAR, TokenType.SLASH, TokenType.PERCENT
    ]:
      token = self.cur_token
      self._eat(token.type)
      factor = ASTNode(ASTNodeType.ARITHMETIC, token, [factor, self._factor()])
    return factor

  def _factor(self) -> ASTNode:
    if self.cur_token.type == TokenType.LEFT_PAREN:
      self._eat(TokenType.LEFT_PAREN)
      expr = self._logic()
      self._eat(TokenType.RIGHT_PAREN)
      return expr
    if self.cur_token.type in [TokenType.PLUS, TokenType.MINUS]:
      return self._unary()
    return self._value()

  def _unary(self) -> ASTNode:
    token = self.cur_token
    if token.type in [TokenType.PLUS, TokenType.MINUS]:
      self._eat(token.type)
    return ASTNode(ASTNodeType.UNARY, token, [self._factor()])

  # ========================================================================= #
  # Public API                                                                #
  # ========================================================================= #

  @property
  def cur_token(self) -> Token:
    """
    Get the current token from the lexer.
    """
    return self._cur_token

  def parse(self) -> ASTNode:
    """
    Parse the input program and return the abstract syntax tree (AST).
    """
    self._cur_token = self._lexer.next_token()
    return self._statements()
